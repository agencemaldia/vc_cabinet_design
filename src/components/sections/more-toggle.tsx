"use client";

import type { ReactNode } from "react";

/** "Read more / Show less" link-style button with a chevron that turns over when open. */
export function MoreToggle({
  open,
  controls,
  onToggle,
  children,
}: {
  open: boolean;
  controls: string;
  onToggle: () => void;
  children: ReactNode;
}) {
  return (
    <button type="button" className="vc-readmore" aria-expanded={open} aria-controls={controls} onClick={onToggle}>
      {children}
      <svg
        width="14"
        height="14"
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth="2"
        strokeLinecap="round"
        strokeLinejoin="round"
        aria-hidden="true"
      >
        <path d="M6 9l6 6 6-6" />
      </svg>
    </button>
  );
}
